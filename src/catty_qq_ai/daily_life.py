def _hash_seed(scope: str, today: str) -> int:
    """把 (scope, 日期) 哈希成 32bit 整数,给 Random 当种子。"""
    raw = f"{scope}|{today}".encode("utf-8")
    digest = hashlib.md5(raw).digest()
    return int.from_bytes(digest[:4], "big")


def _season_bucket(now: datetime | None = None) -> str:
    month = (now or datetime.now()).month
    if 3 <= month <= 5:
        return "spring"
    if 6 <= month <= 8:
        return "summer"
    if 9 <= month <= 11:
        return "autumn"
    return "winter"


def _weather_signal(text: str | None) -> str:
    if not text:
        return ""
    lower = text.lower()
    for weather, keywords in _WEATHER_KEYWORDS.items():
        for kw in keywords:
            if kw in lower:
                return weather
    return ""


def _time_bucket(now: datetime | None = None) -> str:
    h = (now or datetime.now()).hour
    if 5 <= h < 11:
        return "morning"
    if 11 <= h < 14:
        return "noon"
    if 14 <= h < 18:
        return "afternoon"
    if 18 <= h < 23:
        return "evening"
    return "late_night"


_ACTIVITIES_BY_BUCKET = {
    "morning": _ACTIVITIES_MORNING,
    "noon": _ACTIVITIES_NOON,
    "afternoon": _ACTIVITIES_AFTERNOON,
    "evening": _ACTIVITIES_EVENING,
    "late_night": _ACTIVITIES_LATE_NIGHT,
}


def build_daily_life_state(
    scope: str,
    *,
    now: datetime | None = None,
    include_wish: bool | None = None,
    recent_text: str | None = None,
) -> dict[str, str]:
    """返回今天该 scope 的笨猫状态字典,供 prompt 构造使用。

    deterministic by (scope, date) - 同一天同一群每次调用结果一致。
    时段(activity 子池)按 now 实时变,但 RNG seed 不变,所以早/午/晚换 activity 但 mood 不换。

    recent_text: 当前对话的最近文本(主要是本条用户消息),用于从 topical 子池
    优先抽 activity/event/wish/mood 让状态跟话题对得上。为空时退化成原有纯随机。
    """
    now = now or datetime.now()
    today = now.date().isoformat()
    rng = Random(_hash_seed(scope, today))

    topics = detect_topics(recent_text)
    season = _season_bucket(now)
    weather = _weather_signal(recent_text)
    season_rng = Random(_hash_seed(scope, today + ":season:" + season))
    weather_rng = Random(_hash_seed(scope, today + ":weather:" + (weather or "none")))

    bucket = _time_bucket(now)
    activity_pool = _ACTIVITIES_BY_BUCKET[bucket]
    # 让 activity 在时段切换时变化:在 seed 上再叠 bucket
    sub_rng = Random(_hash_seed(scope, today + ":" + bucket))
    if topics:
        picked = pick_topical(topics, _TOPICAL_ACTIVITIES, list(activity_pool), sub_rng, 1)
        activity = picked[0] if picked else sub_rng.choice(activity_pool)
    else:
        activity = sub_rng.choice(activity_pool)
    season_pool = _SEASONAL_ACTIVITIES.get(season, ())
    if season_pool and season_rng.random() < 0.35:
        activity = season_rng.choice(season_pool)

    if topics:
        picked_ev = pick_topical(topics, _TOPICAL_RECENT_EVENTS, list(_RECENT_EVENTS), rng, 1)
        recent_event = picked_ev[0] if picked_ev else rng.choice(_RECENT_EVENTS)
    else:
        recent_event = rng.choice(_RECENT_EVENTS)
    seasonal_events = _SEASONAL_RECENT_EVENTS.get(season, ())
    if seasonal_events and season_rng.random() < 0.25:
        recent_event = season_rng.choice(seasonal_events)

    # mood:优先看 topic-mood,能命中就用;否则全池抽
    mood_label, mood_tone = rng.choice(_MOOD_COLORS)
    if topics:
        topical_mood_pool: list[tuple[str, str]] = []
        for t in topics:
            topical_mood_pool.extend(_TOPICAL_MOODS.get(t, []))
        if topical_mood_pool:
            mood_label, mood_tone = rng.choice(topical_mood_pool)

    if include_wish is None:
        include_wish = rng.random() < 0.4
    if include_wish:
        if topics:
            picked_w = pick_topical(topics, _TOPICAL_WISHES, list(_LITTLE_WISHES), rng, 1)
            wish = picked_w[0] if picked_w else rng.choice(_LITTLE_WISHES)
        else:
            wish = rng.choice(_LITTLE_WISHES)
        seasonal_wishes = _SEASONAL_WISHES.get(season, ())
        if seasonal_wishes and season_rng.random() < 0.3:
            wish = season_rng.choice(seasonal_wishes)
    else:
        wish = ""

    season_flavor = ""
    if season_pool:
        season_flavor = season_rng.choice(season_pool)
    weather_flavor = ""
    if weather:
        weather_pool = _WEATHER_FLAVORS.get(weather, ())
        if weather_pool:
            weather_flavor = weather_rng.choice(weather_pool)

    return {
        "bucket": bucket,
        "season": season,
        "weather": weather,
        "activity": activity,
        "recent_event": recent_event,
        "mood_label": mood_label,
        "mood_tone": mood_tone,
        "wish": wish,
        "season_flavor": season_flavor,
        "weather_flavor": weather_flavor,
    }


def build_daily_life_prompt(
    scope: str,
    *,
    now: datetime | None = None,
    recent_text: str | None = None,
) -> str:
    """返回可直接 push 进 messages 的 system prompt 字符串。

    格式:简短结构化,让主 AI 自然带出但别每条都列。
    传入 recent_text 会让状态优先跟当前话题对齐。
    """
    s = build_daily_life_state(scope, now=now, recent_text=recent_text)
    lines = [
        "【今日笨猫·生活感锚定】",
        f"- 当前在做: {s['activity']}",
        f"- 刚才发生的小事: {s['recent_event']}",
        f"- 今天心情底色: {s['mood_label']} — {s['mood_tone']}",
    ]
    if s["season_flavor"]:
        lines.append(f"- 季节小调味: {s['season_flavor']}(只当背景氛围,不要硬报季节)")
    if s["weather_flavor"]:
        lines.append(f"- 天气/话题调味: {s['weather_flavor']}")
    if s["wish"]:
        lines.append(f"- 心里偷偷想着: {s['wish']}(不要直接说出来,可以在合适时机暴露一点点)")
    lines.append(
        "↑ 这是你今天真实的生活状态,聊天时可以自然带出来(『今天...』『刚才...』『我现在...』),"
        "但**不要每条都报告**,只在话题合适、有人问起、或需要给一句生活感时轻轻露一点。"
        "不要把这段当 todo 复述,要像猫猫一样自然流露。"
    )
    return "\n".join(lines)


# ── 工具:供测试/调试用 ────────────────────────────────────────────
def preview_today(scopes: Iterable[str]) -> list[str]:
    """给一批 scope 预览今天的状态(调试用)。"""
    out = []
    for scope in scopes:
        s = build_daily_life_state(scope)
        out.append(
            f"[{scope}] {s['bucket']} | {s['mood_label']} | {s['activity']} | "
            f"事件={s['recent_event']} | 愿望={s['wish'] or '-'}"
        )
    return out


