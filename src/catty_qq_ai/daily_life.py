def _legacy_detect_topics(text: str | None) -> set[str]:
    """旧 keyword 子串匹配 — 保留作 fallback / 跟 NLU 求 union."""
    if not text:
        return set()
    lower = text.lower()
    hits: set[str] = set()
    for topic, keywords in TOPIC_KEYWORDS.items():
        for kw in keywords:
            if kw in lower:
                hits.add(topic)
                break
    return hits


def detect_topics(text: str | None) -> set[str]:
    """文本 → 命中的主题集合.

    主人 2026-05-28: 加 text2vec embedding union 路径.
    - 旧 keyword 永远跑 (保 recall, 不丢命中)
    - 配 text2vec 开 → 加 cosine 相似度 ≥ threshold 的命中也加进 set
    - 失败 / 关闭 / 空文本 → 仅 keyword 行为, 跟旧版完全一致
    """
    hits_regex = _legacy_detect_topics(text)
    if not text:
        return hits_regex
    try:
        from nonebot import get_plugin_config
        from .config import Config
        cfg = get_plugin_config(Config)
    except Exception:
        return hits_regex
    if not bool(getattr(cfg, "catty_use_text2vec", False)):
        return hits_regex

    try:
        from .nlu import text2vec_engine, prototypes
    except Exception:
        return hits_regex

    emb = text2vec_engine.embed_sync(text)
    if emb is None:
        return hits_regex
    proto = prototypes.get_topic_prototypes()
    if proto is None or proto.shape[0] != len(prototypes.TOPIC_ORDER):
        return hits_regex
    try:
        sims = proto @ emb  # (N_topics,), proto 跟 emb 都已 L2-normalize
    except Exception:
        return hits_regex
    threshold = float(getattr(cfg, "catty_text2vec_topic_threshold", 0.55))
    hits_emb = {
        topic for topic, s in zip(prototypes.TOPIC_ORDER, sims) if float(s) >= threshold
    }
    return hits_regex | hits_emb


async def detect_topics_async(text: str | None) -> set[str]:
    """异步版本 — async caller (主 reply pipeline) 用. 不阻塞 event loop."""
    import asyncio
    return await asyncio.to_thread(detect_topics, text)


def pick_topical(
    topics: Iterable[str],
    topical_pools: dict[str, list[str] | tuple[str, ...]],
    fallback: list[str] | tuple[str, ...],
    rng: Random,
    count: int,
    *,
    topical_ratio: float = 0.7,
) -> list[str]:
    """根据命中 topics 从 topical_pools 优先抽样, 不够用 fallback 补齐。"""
    count = max(0, count)
    if count == 0:
        return []
    candidates: list[str] = []
    seen: set[str] = set()
    for t in topics:
        for entry in topical_pools.get(t, ()):
            if entry not in seen:
                seen.add(entry)
                candidates.append(entry)
    n_topical_target = round(count * topical_ratio)
    n_topical = min(n_topical_target, count, len(candidates))
    result: list[str] = []
    if n_topical > 0:
        result.extend(rng.sample(candidates, k=n_topical))
    remaining = count - len(result)
    if remaining > 0 and fallback:
        used = set(result)
        rest = [x for x in fallback if x not in used]
        if rest:
            result.extend(rng.sample(rest, k=min(remaining, len(rest))))
    return result


