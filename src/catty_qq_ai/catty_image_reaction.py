def detect_image_reaction(image_description: str) -> str:
    """从 image_description 推断 reaction tag, 没命中返回 "."""
    if not image_description or not isinstance(image_description, str):
        return ""
    lower = image_description.lower()
    for tag, keywords, _hint in _IMAGE_REACTION_RULES:
        for kw in keywords:
            if kw in lower:
                return tag
    return ""


def build_image_reaction_prompt(image_description: str) -> str:
    """构建笨猫图片反应 hint. 没命中返回 "."""
    if not image_description:
        return ""
    tag = detect_image_reaction(image_description)
    if not tag:
        return ""
    for t, _kw, hint in _IMAGE_REACTION_RULES:
        if t == tag:
            return (
                f"【笨猫·看图反应 ({tag})】\n"
                f"{hint}\n"
                "(用 image_description 自动检测的反应方向, 让笨猫**不只是复述图**, "
                "而是有具体情绪反应.)"
            )
    return ""


