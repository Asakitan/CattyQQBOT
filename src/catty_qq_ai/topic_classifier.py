def classify_topic(text: str) -> list[str]:
    """对单条消息做多标签话题分类,返回命中的 topic 列表,最多 3 个。"""
    if not text or not isinstance(text, str):
        return []
    lowered = text.lower()
    hits: list[str] = []
    for topic, keywords in _TOPICS.items():
        for kw in keywords:
            if kw.lower() in lowered or kw in text:
                hits.append(topic)
                break  # 一个 topic 命中即可,不重复
    return hits[:3]


def build_topic_context(text: str) -> str:
    """主回复链路用:返回 system prompt 文本。无命中返回空。"""
    topics = classify_topic(text)
    if not topics:
        return ""
    parts: list[str] = []
    for t in topics:
        hint = _TAG_HINTS.get(t, "")
        if hint:
            parts.append(f"`{t}`→{hint}")
    if not parts:
        return ""
    return "群友消息话题领域(供你定基调,不要在回复里复读): " + "; ".join(parts) + "。"


def known_topics() -> Iterable[str]:
    return _TOPICS.keys()
