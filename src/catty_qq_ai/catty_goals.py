def _merge_topical(pools: list[dict[str, list[str]]]) -> dict[str, list[str]]:
    """合并多个 tier 池子 → 单个 topic 查表,同 topic 下拼接。"""
    merged: dict[str, list[str]] = {}
    for pool in pools:
        for topic, entries in pool.items():
            merged.setdefault(topic, []).extend(entries)
    return merged


def _hash_seed(scope: str, today: str, salt: str = "") -> int:
    """把 (scope, 日期[, salt]) 哈希成 32bit 整数, 给 Random 当种子。"""
    raw = f"goals|{scope}|{today}|{salt}".encode("utf-8")
    digest = hashlib.md5(raw).digest()
    return int.from_bytes(digest[:4], "big")


