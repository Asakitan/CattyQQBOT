# 主题 → 池子 的查表,方便 get_today_goals 根据 tier 使用
_TOPICAL_BY_TIER: dict[str, list[dict[str, list[str]]]] = {
    "stranger": [_TOPICAL_GOALS_NEUTRAL, _TOPICAL_GOALS_MISCHIEF],
    "intimate": [_TOPICAL_GOALS_NEUTRAL, _TOPICAL_GOALS_MISCHIEF, _TOPICAL_GOALS_AFFECTIONATE],
    "owner": [_TOPICAL_GOALS_NEUTRAL, _TOPICAL_GOALS_MISCHIEF, _TOPICAL_GOALS_AFFECTIONATE, _TOPICAL_GOALS_OWNER],
}


def _merge_topical(pools: list[dict[str, list[str]]]) -> dict[str, list[str]]:
    """合并多个 tier 池子 → 单个 topic 查表,同 topic 下拼接。"""
    merged: dict[str, list[str]] = {}
    for pool in pools:
        for topic, entries in pool.items():
            merged.setdefault(topic, []).extend(entries)
    return merged


def _hash_seed(scope: str, today: str, salt: str = "") -> int:
    """把 (scope, 日期[, salt]) 哈希成 32bit 整数, 给 Random 当种子。"""
    raw = f"goals|{scope}|{today}|{salt}".encode("utf-8")
    digest = hashlib.md5(raw).digest()
    return int.from_bytes(digest[:4], "big")


def get_today_goals(
    scope: str,
    *,
    now: datetime | None = None,
    affection_level: int = 0,
    is_owner: bool = False,
    count: int = 3,
    recent_text: str | None = None,
) -> list[str]:
    """返回今天该 scope 该用户的 N 条小目标 (deterministic by scope+date+user-tier)。

    分桶规则:
    - 主人 (is_owner=True): 中性 + 淘气 + 撒娇 + 主人专属 全开
    - Lv3+ 普通用户 (亲密): 中性 + 淘气 + 撒娇
    - Lv0-2 普通用户 / 陌生人: 只中性 + 淘气

    user tier 也喂进 seed,所以同一天同 scope 不同 tier 的用户抽到不同目标。

    recent_text: 当前对话最近文本,能提取到 topic 时会从对应 topical 子池优先抽 ~70%,
    剩下从 tier 全池随机补齐; 为空时退化为原有纯 deterministic 随机。
    """
    now = now or datetime.now()
    today = now.date().isoformat()

    pool: list[str] = list(_GOALS_NEUTRAL) + list(_GOALS_MISCHIEF)
    tier = "stranger"
    if is_owner:
        pool += list(_GOALS_AFFECTIONATE) + list(_GOALS_OWNER_ONLY)
        tier = "owner"
    elif affection_level >= 3:
        pool += list(_GOALS_AFFECTIONATE)
        tier = "intimate"

    rng = Random(_hash_seed(scope, today, salt=tier))
    n = max(1, min(count, len(pool)))

    topics = detect_topics(recent_text)
    if topics:
        topical_pool = _merge_topical(_TOPICAL_BY_TIER[tier])
        picked = pick_topical(topics, topical_pool, pool, rng, n, topical_ratio=0.7)
        if picked:
            return picked
    return rng.sample(pool, k=n)


def build_catty_goals_prompt(
    scope: str,
    *,
    now: datetime | None = None,
    affection_level: int = 0,
    is_owner: bool = False,
    count: int = 3,
    recent_text: str | None = None,
) -> str:
    """返回 prompt 注入段。空 scope 返回空字符串。

    传入 recent_text 会让抽到的小心思跟当前话题对得上。
    """
    if not scope:
        return ""
    goals = get_today_goals(
        scope,
        now=now,
        affection_level=affection_level,
        is_owner=is_owner,
        count=count,
        recent_text=recent_text,
    )
    if not goals:
        return ""
    lines = ["【笨猫·今日小心思 (daily_goals)】"]
    for g in goals:
        lines.append(f"- {g}")
    lines.append(
        "↑ 这是你今天的内在动机, 会驱动你主动找机会暴露 / 实施 / 暗示, 但**不能直接报告给用户**"
        "(不要说『人家今天想撒娇 3 次喵』这种)。要像有自己想法的人一样, 在话题合适时自然带出来。"
    )
    return "\n".join(lines)


