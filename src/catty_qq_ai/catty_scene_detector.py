def detect_scene(text: str) -> str:
    """返回当前消息匹配的场景 tag (最高优先级命中), 没命中返回 ""。"""
    if not text or not isinstance(text, str):
        return ""
    lower = text.lower()
    best_tag = ""
    best_priority = -1
    for tag, priority, keywords, _ in _SCENE_DEFS:
        if priority <= best_priority:
            continue
        for kw in keywords:
            if kw in lower:
                best_tag = tag
                best_priority = priority
                break
    return best_tag


def build_scene_detector_prompt(text: str) -> str:
    """构建注入用的 prompt 段。没命中返回 ""(skip register)。"""
    tag = detect_scene(text)
    if not tag:
        return ""
    for s_tag, _, _, hint in _SCENE_DEFS:
        if s_tag == tag:
            return f"【当前消息场景: {tag}】\n{hint}\n(这是这一条消息的临时场景判定, 只影响这一条回复的反应方式。)"
    return ""


