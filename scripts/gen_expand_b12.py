def dump_route(r):
    """手写 dump 保留指定字段顺序和 quote 规则"""
    lines = []
    lines.append(f"- name: {r['name']}")
    lines.append(f"  intent: {r['intent']}")
    # keywords - 用 flow 形式 (跟原文一样)
    kw_items = []
    for k in r['keywords']:
        s = str(k)
        # 如含特殊字符或纯数字, quote
        if any(c in s for c in [':', '{', '}', '[', ']', ',', '#', '&', '*', '!', '|', '>', "'", '"', '%', '@', '`']) or s.strip().isdigit() or s.startswith(' ') or s.startswith('-'):
            kw_items.append(f'"{s}"')
        else:
            kw_items.append(s)
    lines.append(f"  keywords: [{', '.join(kw_items)}]")
    # utterances
    lines.append('  utterances:')
    for u in r['utterances']:
        s = str(u)
        # 强制 quote 条件: 含 {, :, #, ", 行首-, 纯数字, 含%等
        needs_quote = (
            s.startswith('{') or
            any(c in s for c in [':', '#', '"', '%', '*', '&', '!']) or
            s.strip().startswith('-') or
            s.strip().isdigit() or
            s.strip().replace('.','').isdigit()
        )
        if needs_quote:
            esc = s.replace('"', '\\"')
            lines.append(f'    - "{esc}"')
        else:
            lines.append(f'    - {s}')
    # responses (强制双引号)
    lines.append('  responses:')
    for rsp in r['responses']:
        s = str(rsp)
        esc = s.replace('"', '\\"')
        lines.append(f'    - "{esc}"')
    lines.append(f"  cooldown_seconds: {r.get('cooldown_seconds', 60)}")
    lines.append(f"  weight: {r.get('weight', 1.0)}")
    if 'disambiguate_context' in r:
        lines.append(f"  disambiguate_context: {r['disambiguate_context']}")
    return '\n'.join(lines)

def process_file(stem):
    p = ROUTES / f'{stem}.yaml'
    text = p.read_text(encoding='utf-8')
    # 提取头部注释
    header_lines = []
    for line in text.splitlines():
        if line.strip().startswith('#') or line.strip() == '':
            header_lines.append(line)
        else:
            break
    header = '\n'.join(header_lines).rstrip() + '\n\n'
    data = yaml.safe_load(text)
    new_routes = [expand_route(r) for r in data]
    body = '\n\n'.join(dump_route(r) for r in new_routes)
    p.write_text(header + body + '\n', encoding='utf-8')
    return len(new_routes)

