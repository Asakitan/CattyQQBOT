def render_subs(prefix: str, subs):
    lines = []
    for i, item in enumerate(subs, 1):
        intent, _, kws, utts, resps = item
        name = f"{prefix}_{i:03d}"
        lines.append(f"- name: {name}")
        lines.append(f"  intent: {intent}")
        lines.append(f"  keywords:")
        for k in kws:
            lines.append(f"    - {k}")
        lines.append(f"  utterances:")
        for u in utts:
            u_esc = u.replace('"', '\\"')
            lines.append(f'    - "{u_esc}"')
        lines.append(f"  responses:")
        for r in resps:
            r_esc = r.replace('"', '\\"')
            lines.append(f'    - "{r_esc}"')
        lines.append(f"  cooldown_seconds: 60")
        lines.append(f"  weight: 1.0")
        lines.append("")
    return "\n".join(lines)


