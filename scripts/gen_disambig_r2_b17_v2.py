def base_key(file):
    s = file.replace('.yaml','')
    # 去除前导 [A-Z]+ 大写前缀 数字_ 之类
    s = re.sub(r'^[A-Z]+\d*_', '', s)
    s = re.sub(r'^\d+_', '', s)
    return s

def slug_tokens(slug):
    return re.split(r'[_\-]', slug.lower())

def gen_ctx(r):
    file = r['file']
    keywords = set(r['keywords'])
    base = base_key(file)
    candidates = []
    if base in TOPIC_BANK:
        candidates = list(TOPIC_BANK[base])
        hit = True
    else:
        hit = False
        toks = slug_tokens(base)
        for t in toks:
            if t in FILE_HINTS:
                candidates.extend(FILE_HINTS[t])
        seen=set(); uniq=[]
        for c in candidates:
            if c not in seen:
                seen.add(c); uniq.append(c)
        candidates = uniq
    # 过滤 keywords 重叠 + 长度
    out=[]
    for c in candidates:
        if c in keywords: continue
        if not (2<=len(c)<=4): continue
        if c not in out:
            out.append(c)
        if len(out)>=6: break
    # 不足补 intent
    if len(out)<4:
        intent = r.get('intent','')
        extra = {'complaint':['累','呜','烦','难受'],
                 'question':['推荐','怎么','哪种','好不好'],
                 'playful':['嘿嘿','逗','蹭蹭','嘻嘻']}.get(intent, ['日常','聊聊','陪陪','蹭蹭'])
        for e in extra:
            if e not in out and e not in keywords:
                out.append(e)
            if len(out)>=5: break
    return out[:6], hit

