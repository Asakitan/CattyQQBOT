processed = []
skipped = []

for stem in stems:
    path = os.path.join(ROUTES_DIR, f'{stem}.yaml')
    if not os.path.exists(path):
        skipped.append((stem, 'not found'))
        continue
    theme = THEMES.get(stem)
    if not theme:
        skipped.append((stem, 'no theme'))
        continue
    # 保留文件头注释
    raw = open(path, 'r', encoding='utf-8').read()
    header_lines = []
    for line in raw.splitlines():
        if line.startswith('#') or line.strip() == '':
            header_lines.append(line)
        else:
            break
    header = '\n'.join(header_lines).rstrip() + '\n\n'

    data = yaml.safe_load(raw)
    if not isinstance(data, list):
        skipped.append((stem, 'not list'))
        continue

    kw_pool = theme['kw']
    utt_pool = theme['utt']
    resp_pool = RESP_POOL[theme['topic']]

    for sub in data:
        expand_one_sub(sub, kw_pool, utt_pool, resp_pool)

    # 写回: 用紧凑 yaml dump,保留 key 顺序 (PyYAML 默认会按字母, 我们手动按指定顺序)
    KEY_ORDER = ['name','intent','keywords','utterances','responses',
                 'cooldown_seconds','weight','disambiguate_context']
    def emit_list(lines, k, v):
        lines.append(f'  {k}:')
        for item in v:
            s = str(item)
            esc = s.replace('"', r'\"')
            lines.append(f'    - "{esc}"')

    def emit_scalar(lines, k, v):
        if isinstance(v, (int, float)):
            lines.append(f'  {k}: {v}')
        else:
            lines.append(f'  {k}: {v}')

    out_lines = [header.rstrip()]
    for sub in data:
        block_lines = []
        # name first as list element
        name_val = sub.get('name', '')
        block_lines.append(f'- name: {name_val}')
        for k in KEY_ORDER:
            if k == 'name' or k not in sub:
                continue
            v = sub[k]
            if isinstance(v, list):
                emit_list(block_lines, k, v)
            else:
                emit_scalar(block_lines, k, v)
        for k, v in sub.items():
            if k in KEY_ORDER:
                continue
            if isinstance(v, list):
                emit_list(block_lines, k, v)
            else:
                emit_scalar(block_lines, k, v)
        out_lines.append('\n'.join(block_lines))
    out = '\n\n'.join(out_lines).rstrip() + '\n'
    open(path, 'w', encoding='utf-8').write(out)
    processed.append(stem)
    print(f'[OK] {stem}')

print(f'\n=== summary ===')
print(f'processed: {len(processed)}/16')
