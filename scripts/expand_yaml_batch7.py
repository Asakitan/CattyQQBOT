import yaml

def load_yaml(path):
    return yaml.safe_load(open(path, 'r', encoding='utf-8'))

def expand_one_sub(sub, kw_pool, utt_pool, resp_pool, user_addr='{user_addr}'):
    """对单个 sub-route 扩展 keywords/utterances/responses"""
    # keywords -> 8-10
    kws = list(sub.get('keywords', []) or [])
    seen = set(kws)
    for w in kw_pool:
        if len(kws) >= 9:
            break
        if w not in seen:
            kws.append(w); seen.add(w)
    sub['keywords'] = kws[:10]

    # utterances -> 10-12
    utts = list(sub.get('utterances', []) or [])
    seen_u = set(utts)
    for u in utt_pool:
        if len(utts) >= 11:
            break
        if u not in seen_u:
            utts.append(u); seen_u.add(u)
    sub['utterances'] = utts[:12]

    # responses -> 8
    resps = list(sub.get('responses', []) or [])
    seen_r = set(resps)
    for r in resp_pool:
        if len(resps) >= 8:
            break
        if r not in seen_r:
            resps.append(r); seen_r.add(r)
    # 若 resp_pool 不够,循环补充并加变体
    idx = 0
    while len(resps) < 8:
        cand = resp_pool[idx % len(resp_pool)] + ' '
        # 加微小后缀避免重复
        cand2 = cand.strip()
        if cand2 not in seen_r:
            resps.append(cand2); seen_r.add(cand2)
        idx += 1
        if idx > 50: break
    sub['responses'] = resps[:8]
    return sub

