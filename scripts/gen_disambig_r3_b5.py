def write_yaml(stem: str, sub_routes_meta: list):
    """根据 EXPAND 字典写出 yaml 文件, sub_routes_meta = [(name, intent, cooldown, weight, header_extra), ...]"""
    out_lines = []
    out_lines.append(f"# {stem} routes (S6 R802+ ultracode round3 扩充, 主人 2026-05-30)")
    out_lines.append("# 日常聊天微互动, 笨猫语气活泼傲娇, kw>=8 utt>=10 resp>=8")
    out_lines.append("")
    for i, (name, intent, cooldown, weight, extras) in enumerate(sub_routes_meta, 1):
        data = EXPAND[(stem, i)]
        out_lines.append(f"- name: {name}")
        out_lines.append(f"  intent: {intent}")
        out_lines.append(f"  keywords: [{', '.join(data['keywords'])}]")
        out_lines.append("  utterances:")
        for u in data['utterances']:
            if u.startswith('"'):
                out_lines.append(f"    - {u}")
            else:
                out_lines.append(f"    - {u}")
        out_lines.append("  responses:")
        for r in data['responses']:
            out_lines.append(f"    - {r}")
        out_lines.append(f"  cooldown_seconds: {cooldown}")
        out_lines.append(f"  weight: {weight}")
        if extras:
            for k, v in extras.items():
                out_lines.append(f"  {k}: {v}")
        out_lines.append("")
    return "\n".join(out_lines)


