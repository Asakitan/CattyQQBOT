from pathlib import Path
import yaml

ROUTES_DIR = Path(r"e:/VC/Catty/src/catty_qq_ai/data/cpu_engine/routes")


def gen(stem, items):
    lines = [
        f"# {stem} routes (S6 R802+ ultracode round3 扩充, 主人 2026-05-30)",
        "# 日常聊天微互动, 笨猫语气活泼傲娇, kw>=8 utt>=10 resp>=8",
        "",
    ]
    for name, intent, weight, kw, utt, resp in items:
        assert len(kw) >= 8
        assert len(utt) >= 10
        assert len(resp) >= 8
        lines.append(f"- name: {name}")
        lines.append(f"  intent: {intent}")
        lines.append(f"  keywords: [{', '.join(kw)}]")
        lines.append("  utterances:")
        for u in utt:
            lines.append(f"    - {u}")
        lines.append("  responses:")
        for r in resp:
            lines.append(f"    - {r}")
        lines.append(f"  cooldown_seconds: 60")
        lines.append(f"  weight: {weight}")
        lines.append("")
    content = "\n".join(lines)
    parsed = yaml.safe_load(content)
    assert len(parsed) == 10
    for r in parsed:
        assert len(r["keywords"]) >= 8
        assert len(r["utterances"]) >= 10
        assert len(r["responses"]) >= 8
    (ROUTES_DIR / f"{stem}.yaml").write_text(content, encoding="utf-8")
    print(f"OK {stem}")


